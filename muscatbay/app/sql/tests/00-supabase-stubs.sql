-- Mirrors the review columns in sql/migrations/create_professional_applications.sql.
-- The intake policy references them directly and, unlike the neighbouring
-- contractor_contracts block, does not guard on their existence — so a stub
-- missing them aborts the whole migration, exactly as a live table would.
CREATE TABLE IF NOT EXISTS public.professional_applications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text,
    status text DEFAULT 'pending',
    reviewer_notes text,
    reviewed_by uuid REFERENCES auth.users(id),
    reviewed_at timestamptz
);
